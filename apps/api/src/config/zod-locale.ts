import { z } from "zod";

/**
 * يضبط رسائل Zod الافتراضية على العربية لكل المشروع.
 *
 * المتحقّقات تعتمد النصّ الافتراضي في نحو 180 موضعاً عبر 29 ملفاً، فكانت أخطاء
 * الحقول تصل المستخدم إنجليزية («Invalid email») داخل واجهة عربية بالكامل —
 * حتى بعد تعريب رسائل ApiError، لأن هذه تُولَّد داخل Zod لا في شيفرتنا.
 * الضبط هنا مركزي: يشمل كل مخطّط قائم وأي مخطّط يُضاف لاحقاً بلا عمل إضافي،
 * وأي رسالة مخصّصة مكتوبة في مخطّط بعينه تبقى غالبة عليه.
 *
 * `customError` فوق اللغة العربية الرسمية لحالة واحدة: غياب الحقل أصلاً.
 * ترجمة Zod له «يفترض إدخال string، ولكن تم إدخال undefined» — تسرّب أسماء
 * أنواع برمجية لموظّف الاستقبال. البقية تُترك للترجمة الرسمية المُصانة عند Zod.
 */
export function configureZodArabic(): void {
  const arabic = z.locales.ar();

  z.config({
    ...arabic,
    customError: (issue) => {
      if (issue.code === "invalid_type" && issue.input === undefined) {
        return "هذا الحقل مطلوب.";
      }
      return undefined; // لا رأي لنا ⇒ تُستخدم الترجمة العربية الرسمية
    },
  });
}
